import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const apiRoot = path.join(root, 'app', 'api')
const specPath = path.join(root, 'api-contract', 'openapi.yaml')
const writeReport = process.argv.includes('--write')

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name)
    return entry.isDirectory() ? walk(fullPath) : [fullPath]
  })
}

function routePath(file) {
  const relative = path.relative(path.join(root, 'app'), path.dirname(file)).replaceAll('\\', '/')
  return `/${relative}`.replace(/\[([^\]]+)\]/g, '{$1}')
}

function contractPath(actualPath) {
  return actualPath.startsWith('/api/v1/')
    ? actualPath.slice('/api/v1'.length)
    : null
}

const routeFiles = walk(apiRoot).filter((file) => file.endsWith(`${path.sep}route.ts`))
const actualRoutes = routeFiles.map((file) => {
  const source = fs.readFileSync(file, 'utf8')
  const methods = [...source.matchAll(/export\s+async\s+function\s+(GET|POST|PUT|PATCH|DELETE)\b/g)]
    .map((match) => match[1])
  const actual = routePath(file)
  return { actual, contract: contractPath(actual), methods: methods.join(', ') || '—' }
}).sort((left, right) => left.actual.localeCompare(right.actual))

const spec = fs.readFileSync(specPath, 'utf8')
const documentedPaths = new Set(
  [...spec.matchAll(/^  (\/[^:]+):\s*$/gm)].map((match) => match[1]),
)

const rows = actualRoutes.map((route) => ({
  ...route,
  status: route.contract === null
    ? 'LEGACY_OR_EXTERNAL'
    : documentedPaths.has(route.contract)
      ? 'MAPPED'
      : 'MISSING_IN_OPENAPI',
}))
const implementedContractPaths = new Set(rows.flatMap((row) => row.contract ? [row.contract] : []))
const openApiOnly = [...documentedPaths]
  .filter((documentedPath) => !implementedContractPaths.has(documentedPath))
  .sort()

const lines = [
  '# API route ↔ OpenAPI mapping',
  '',
  '> Generated by `npm run check:api-routes`. Do not edit the table manually.',
  '',
  '## Versioning decision',
  '',
  '- Keep `/api/deposit` and `/api/deposit/quote` temporarily as legacy web endpoints because the current deposit UI calls them.',
  '- New public contract work must use `/api/v1`; migrate the deposit UI before removing the legacy routes.',
  '- Webhooks, Auth0/KYC callbacks, and contract-signing callbacks remain external integration endpoints and are not renamed mechanically.',
  '',
  '| Runtime route | Methods | OpenAPI path | Classification |',
  '|---|---|---|---|',
  ...rows.map((row) => `| \`${row.actual}\` | ${row.methods} | ${row.contract ? `\`${row.contract}\`` : '—'} | ${row.status} |`),
  '',
  '## OpenAPI paths without a matching runtime route',
  '',
  ...(openApiOnly.length ? openApiOnly.map((item) => `- \`${item}\``) : ['- None']),
  '',
]

if (writeReport) {
  fs.writeFileSync(path.join(root, 'docs', 'api-route-mapping.md'), lines.join('\n'))
}

const missing = rows.filter((row) => row.status === 'MISSING_IN_OPENAPI')
console.log(`Runtime routes: ${rows.length}`)
console.log(`Mapped v1 routes: ${rows.filter((row) => row.status === 'MAPPED').length}`)
console.log(`Legacy/external routes: ${rows.filter((row) => row.status === 'LEGACY_OR_EXTERNAL').length}`)
console.log(`Missing in OpenAPI: ${missing.length}`)
console.log(`OpenAPI-only paths: ${openApiOnly.length}`)
if (missing.length) console.log(missing.map((row) => `  ${row.actual}`).join('\n'))
